TEMA 02: CONSTANTES

Una constante representa un valor que no debe reasignarse. Se declara con
`const` o `define` y, por convencion, su nombre va en mayusculas. A diferencia
de las variables, su nombre no empieza con `$`. Las constantes definidas en un
archivo pueden usarse en su ambito global. No guardes como constante un valor
que deba cambiar durante la ejecucion.

Sintaxis:
const IVA = 0.19;
define('NOMBRE_APP', 'Mi aplicacion');
$total = 100 * (1 + IVA);
echo NOMBRE_APP . PHP_EOL;

